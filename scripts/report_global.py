#!/usr/bin/env python3
"""Write the global section of docs/results.md from params_global.json.

Every number in the section is read from web/public/data/params_global.json
(written by fit_harmonization.py); nothing is typed by hand. Re-run after
every global fit. The section sits between two HTML comment markers and is
replaced in place; the rest of results.md is left untouched.

Suspicious-country rules (flags, not removals -- the fits stay published):
  - held-out model R^2 is negative or could not be computed
  - FRP at P=0.5 is undefined, below 1 MW or above 100 MW
  - kappa outside 0.05-2
  - harmonized 2012 step differs from the Aqua-only step by more than 1.5x
    either way (Aqua-only is the null: an unchanged sensor across 2012)
  - model bias beyond +/-50% on held-out years

Usage: python3 scripts/report_global.py
"""

from __future__ import annotations

import json
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PARAMS = ROOT / "web" / "public" / "data" / "params_global.json"
RESULTS = ROOT / "docs" / "results.md"
START, END = "<!-- global:start -->", "<!-- global:end -->"


def f(x, fmt="{:.2f}"):
    return "n/a" if x is None or (isinstance(x, float) and not math.isfinite(x)) else fmt.format(x)


def flags(r: dict) -> list[str]:
    out = []
    t = r["validation_test"]["model"]
    nc = r["null_control"]
    if t["r2"] is None:
        out.append("test R² undefined")
    elif t["r2"] < 0:
        out.append(f"test R² {t['r2']:.2f}")
    p50 = r["frp_at_p50_mw"]
    if p50 is None or not (1 <= p50 <= 100):
        out.append(f"P=0.5 at {f(p50, '{:.1f}')} MW")
    if not (0.05 <= r["kappa"] <= 2):
        out.append(f"κ {r['kappa']:.3f}")
    a, h = nc.get("aqua_only_step_ratio_2012"), nc.get("harmonized_step_ratio_2012")
    if a and h and math.isfinite(a) and math.isfinite(h) and a > 0 and h > 0:
        if max(h / a, a / h) > 1.5:
            out.append(f"step {h:.2f}× vs Aqua {a:.2f}×")
    else:
        out.append("step ratio undefined")
    if t["bias_pct"] is not None and abs(t["bias_pct"]) > 50:
        out.append(f"bias {t['bias_pct']:+.0f}%")
    return out


def section(p: dict) -> str:
    C = p["countries"]
    own = {k: r for k, r in C.items() if r["fit_source"] == "own"}
    pooled = {k: r for k, r in C.items() if r["fit_source"] == "pooled"}
    order = sorted(C, key=lambda k: -C[k]["n_train_viirs_detections"])
    flagged = {k: flags(C[k]) for k in order}
    flagged = {k: v for k, v in flagged.items() if v}
    pm = p.get("pooled_model") or {}
    beats_raw = sum(1 for r in C.values() if r["validation_test"]["model"]["r2"] is not None
                    and r["validation_test"]["raw_viirs"]["r2"] is not None
                    and r["validation_test"]["model"]["r2"] > r["validation_test"]["raw_viirs"]["r2"])
    L = [START, "", "## Global run — every FIRMS country", "",
         f"Fit version `{p['fit_version']}`. Generated by `scripts/report_global.py` from "
         "`web/public/data/params_global.json`; same method, train/test split and match rule as above "
         f"(train {p['train_years'][0]}–{p['train_years'][1]}, test {p['test_years'][0]}–{p['test_years'][1]}, "
         f"drift era {p['drift_years'][0]}–{p['drift_years'][1]} never fitted).", "",
         f"- Countries fitted: **{len(C)}** ({len(own)} own curve, {len(pooled)} pooled curve). "
         f"Too sparse to evaluate (no harmonized series published): **{len(p['failed'])}**.",
         f"- Pooled curve: detection-weighted mean of the own-fit countries fitted before it was formed "
         f"({len(pm.get('from_countries', []))} countries); b0 {f(pm.get('b0'), '{:.3f}')}, "
         f"b1 {f(pm.get('b1'), '{:.3f}')}, κ {f(pm.get('kappa'), '{:.3f}')}.",
         f"- Model beats raw VIIRS on held-out R² in **{beats_raw} of {len(C)}** fitted countries.",
         "- Regression check: Portugal, Chile, Australia and Canada reproduce `params.json` "
         "(R², bias, FRP at P=0.5, κ, step ratios) to floating-point precision.",
         "- Claims stay regional: these are per-country fits, not a global step correction.", "",
         "### All fitted countries (largest training sample first)", "",
         "| Country | Fit | Test R² model | Test R² raw VIIRS | Bias | FRP at P=0.5 | κ | Step raw / Aqua / harmonized | Train detections |",
         "|---|---|---|---|---|---|---|---|---|"]
    for k in order:
        r = C[k]; t = r["validation_test"]; nc = r["null_control"]
        L.append(f"| {k.replace('_', ' ')} | {r['fit_source']} | {f(t['model']['r2'])} | {f(t['raw_viirs']['r2'], '{:.1f}')} | "
                 f"{f(t['model']['bias_pct'], '{:+.1f}%')} | {f(r['frp_at_p50_mw'], '{:.1f} MW')} | {r['kappa']:.3f} | "
                 f"{f(nc['spliced_raw_step_ratio_2012'])}× / {f(nc['aqua_only_step_ratio_2012'])}× / "
                 f"{f(nc['harmonized_step_ratio_2012'])}× | {r['n_train_viirs_detections']:,} |")
    L += ["", f"### Suspicious results ({len(flagged)} countries) — flagged, not hidden", "",
          "Rules: negative or undefined held-out R²; FRP at P=0.5 undefined or outside 1–100 MW; κ outside "
          "0.05–2; harmonized 2012 step more than 1.5× away from the Aqua-only step; held-out bias beyond ±50%.", "",
          "| Country | Fit | Flags |", "|---|---|---|"]
    for k, v in flagged.items():
        L.append(f"| {k.replace('_', ' ')} | {C[k]['fit_source']} | {'; '.join(v)} |")
    L += ["", f"### Not fitted ({len(p['failed'])}) — too sparse to evaluate", "",
          ", ".join(k.replace("_", " ") for k in sorted(p["failed"])) + ".", "",
          "These have raw calendars only; the app must show them as uncorrected.", "", END]
    return "\n".join(L)


def main() -> int:
    p = json.loads(PARAMS.read_text())
    s = section(p)
    text = RESULTS.read_text()
    if START in text:
        text = text[:text.index(START)] + s + text[text.index(END) + len(END):]
    else:
        text = text.rstrip("\n") + "\n\n" + s + "\n"
    RESULTS.write_text(text)
    C = p["countries"]
    fl = {k: flags(r) for k, r in C.items()}
    print(f"{len(C)} fitted, {len(p['failed'])} failed, {sum(1 for v in fl.values() if v)} flagged")
    return 0


if __name__ == "__main__":
    sys.exit(main())
